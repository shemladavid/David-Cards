	function SealedDuel.alternate(code,anime)
		local chk=anime and 1 or 0
		if not namechange[code] or not namechange[code][chk] then return code end
		local num=Duel.GetRandomNumber(1,#namechange[code][chk])
		return namechange[code][chk][num]
	end
	function SealedDuel.op(e,tp,eg,ep,ev,re,r,rp)
		local sealedOwners={}
		for _,card in ipairs(selfs) do
			sealedOwners[card:GetOwner()]=true
			Duel.SendtoDeck(card,0,-2,REASON_RULE)
		end
		local counts={}
		counts[0]=Duel.GetPlayersCount(0)
		counts[1]=Duel.GetPlayersCount(1)
		Duel.DisableShuffleCheck()
		Duel.Hint(HINT_CARD,0,id)
		--tag variable defining
		local z,o=tp,1-tp
		
		--pack selection
		local selectpack={}
		-- for _,sel in ipairs({Duel.SelectCardsFromCodes(tp,1,1,false,true,511005095,511005096,511005097,511005098,511005099,511005100,511005101)}) do
		-- 	selectpack[sel[2]]=true
		-- end
		local selectedPool=Duel.GetRandomNumber(1,#pack)
		selectpack[selectedPool]=true
		
		--treat as all monster types
		if true then
			local getrc=Card.GetRace
			Card.GetRace=function(c)
				if c:IsMonster() then return 0xfffffff end
				return getrc(c)
			end
			local getorigrc=Card.GetOriginalRace
			Card.GetOriginalRace=function(c)
				if c:IsMonster() then return 0xfffffff end
				return getorigrc(c)
			end
			local getprevrc=Card.GetPreviousRaceOnField
			Card.GetPreviousRaceOnField=function(c)
				if (c:GetPreviousTypeOnField()&TYPE_MONSTER)~=0 then return 0xfffffff end
				return getprevrc(c)
			end
			local isrc=Card.IsRace
			Card.IsRace=function(c,r)
				if c:IsMonster() then return true end
				return isrc(c,r)
			end
		end

		-- Treat as all monster attributes
		if true then
			local getattr=Card.GetAttribute
			Card.GetAttribute=function(c)
				if c:IsMonster() then return 0x7f end
				return getattr(c)
			end
			local getorigattr=Card.GetOriginalAttribute
			Card.GetOriginalAttribute=function(c)
				if c:IsMonster() then return 0x7f end
				return getorigattr(c)
			end
			local getprevattr=Card.GetPreviousAttributeOnField
			Card.GetPreviousAttributeOnField=function(c)
				if (c:GetPreviousTypeOnField()&TYPE_MONSTER)~=0 then return 0x7f end
				return getprevattr(c)
			end
			local isattr=Card.IsAttribute
			Card.IsAttribute=function(c,a)
				if c:IsMonster() then return true end
				return isattr(c,a)
			end
		end


		--anime counterparts select
		anime=true
			
		--anime counterparts
		local groups={}
		groups[0]={}
		groups[1]={}
		for i=1,counts[0] do
			groups[0][i]={}
		end
		for i=1,counts[1] do
			groups[1][i]={}
		end
		
		for p=z,o do
			for team=1,counts[p] do
				for i=1,60 do
					local packnum=0
					--random set among selected sets
					repeat
						packnum=Duel.GetRandomNumber(1,#pack)
					until selectpack[packnum]
					for i=1,5 do
						local rarity
						if i==1 then
							rarity=1
						elseif i<5 then
							rarity=2
						else
							rarity=3
						end
						local code=pack[packnum][rarity][Duel.GetRandomNumber(1,#pack[packnum][rarity])]
						local finalcode=SealedDuel.alternate(code,anime)
						table.insert(groups[p][team],finalcode)
					end
				end
			end
		end
		
		for p=z,o do
			for team=1,counts[p] do
				Duel.SendtoDeck(Duel.GetFieldGroup(p,0xff,0),nil,-2,REASON_RULE)
				for idx,code in ipairs(groups[p][team]) do
					Debug.AddCard(code,p,p,LOCATION_DECK,1,POS_FACEDOWN_DEFENSE)
				end
				Debug.ReloadFieldEnd()
				-- Duel.Hint(HINT_SELECTMSG,p,aux.Stringid(id,3))
				-- local fg=Duel.GetFieldGroup(p,0xff,0)
				-- local exclude=fg:Select(p,0,#fg,nil)
				-- if exclude then
				-- 	Duel.SendtoDeck(exclude,nil,-2,REASON_RULE)
				-- end
				Duel.ShuffleDeck(p)
				if sealedOwners[p] then
					local extra={}
					for c in aux.Next(Duel.GetFieldGroup(p,LOCATION_EXTRA,0)) do
						table.insert(extra,c)
					end
					local function sortType(c)
						if c:IsType(TYPE_FUSION) then return 1 end
						if c:IsType(TYPE_SYNCHRO) then return 2 end
						if c:IsType(TYPE_XYZ) then return 3 end
						if c:IsType(TYPE_LINK) then return 4 end
						return 5
					end
					local function sortLevel(c)
						if c:IsType(TYPE_XYZ) then return c:GetRank() end
						if c:IsType(TYPE_LINK) then return c:GetLink() end
						return c:GetLevel()
					end
					table.sort(extra,function(a,b)
						-- Keep face-up cards after face-down cards.
						if a:IsFaceup()~=b:IsFaceup() then return not a:IsFaceup() end
						local at,bt=sortType(a),sortType(b)
						if at~=bt then return at>bt end
						local al,bl=sortLevel(a),sortLevel(b)
						if al~=bl then return al>bl end
						if a:GetCode()~=b:GetCode() then return a:GetCode()>b:GetCode() end
						return a:GetSequence()<b:GetSequence()
					end)
					-- In the Extra Deck, MoveSequence appends the card.
					for _,c in ipairs(extra) do
						Duel.MoveSequence(c,0)
					end
				else
					Duel.ShuffleExtra(p)
				end

				local dtpg=Duel.GetDecktopGroup(p,Duel.GetStartingHand(p))
				-- Duel.ConfirmCards(p,dtpg)
				local previewCodes={}
				for previewCard in aux.Next(dtpg) do
					table.insert(previewCodes,previewCard:GetCode())
				end
				if #previewCodes>0 then
					Duel.SelectCardsFromCodes(p,1,1,false,true,table.unpack(previewCodes))
				end
				if Duel.SelectYesNo(p,aux.Stringid(id,4)) then
					Duel.MoveToDeckBottom(dtpg)
				end
				if counts[p]~=1 then
					Duel.TagSwap(p)
				end
			end
		end
		-- Give each Sealed Duel owner one new card after setup.
		for owner=0,1 do
			if sealedOwners[owner] then
				local bonus=Duel.CreateToken(owner,12345761)
				local bonus2=Duel.CreateToken(owner,41235896)
				Duel.MoveToField(bonus,owner,owner,LOCATION_SZONE,POS_FACEUP,true)
				Duel.MoveToField(bonus2,owner,owner,LOCATION_MZONE,POS_FACEUP_ATTACK,true)
			end
		end
	end
	finish_setup()
